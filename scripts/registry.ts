import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// Builds the copy-in version of the component: the modules in src/morph that
// make up <PixelMorph>, joined into one self-contained .tsx file, plus a shadcn
// registry item wrapping it, so
//
//   npx shadcn@latest add https://geist-pixel-animation.vercel.app/r/pixel-morph.json
//
// drops that one file into a project. The site renders the same modules, so
// what people install is exactly what the page shows.

const SRC = join(process.cwd(), 'src', 'morph');
const OUT = join(process.cwd(), 'public', 'r');
const NAME = 'pixel-morph';
const SITE = 'https://geist-pixel-animation.vercel.app';

// Dependency order: each module only uses what comes before it.
const MODULES = ['encoding.ts', 'glyph-data.ts', 'glyphs.ts', 'layout.ts', 'variants.ts', 'ease.ts', 'paint.ts', 'painter.ts', 'PixelMorph.tsx'];
const MAIN = 'PixelMorph.tsx';
// Exports from the helper modules that the installed file should still offer.
const PUBLIC = new Set(['VARIANTS', 'Variant', 'Align']);

const HEADER = `/**
 * PixelMorph: text in Geist Pixel that morphs between its five faces.
 * ${SITE}
 *
 *   <PixelMorph text="hello world" fontSize={96} variant="circle" />
 *
 * Every pixel of the text is drawn on a canvas in the shape of the chosen face
 * (square, triangle, circle, grid or line), or 'salad', every pixel in a face of its own. Change \`variant\` and each pixel
 * morphs into the new shape: solid squares break into dots, dots sharpen into
 * triangles. \`cycle\` keeps it going on its own. Needs React 18 or later;
 * nothing else, not even the font: the pixels of all 420 characters are below.
 *
 * Code: MIT License. Glyphs: read from Geist Pixel by Vercel, SIL Open Font
 * License 1.1.
 *
 * Generated by scripts/registry.ts from the geist-pixel-animation source; edit freely.
 */`;

const reactNames = new Set<string>();
const parts: string[] = [];

for (const file of MODULES) {
  let src = readFileSync(join(SRC, file), 'utf8').replace(/\r\n/g, '\n');

  src = src.replace(/^'use client';\n+/m, '');
  src = src.replace(/^import \{([^}]*)\} from 'react';\n/m, (_, names: string) => {
    for (const n of names.split(',')) if (n.trim()) reactNames.add(n.trim());
    return '';
  });
  // Everything else it imports is one of the modules joined here.
  src = src.replace(/^import [^;]+ from '\.\/[^']+';\n/gm, '');

  if (file !== MAIN) {
    src = src.replace(/^export (const|function|type|class) (\w+)/gm, (whole, kind: string, name: string) =>
      PUBLIC.has(name) ? whole : `${kind} ${name}`,
    );
  }

  parts.push(`// ── ${file} ${'─'.repeat(Math.max(4, 72 - file.length))}\n\n${src.trim()}\n`);
}

const leftover = parts.join('\n').match(/^import .*$/gm);
if (leftover) throw new Error(`unresolved imports in the bundle:\n${leftover.join('\n')}`);

const values = [...reactNames].filter((n) => !n.startsWith('type ')).sort();
const types = [...reactNames].filter((n) => n.startsWith('type ')).sort();
const reactImport = `import { ${[...values, ...types].join(', ')} } from 'react';`;

const tsx = `'use client';\n\n${HEADER}\n\n${reactImport}\n\n${parts.join('\n')}`;

const item = {
  $schema: 'https://ui.shadcn.com/schema/registry-item.json',
  name: NAME,
  type: 'registry:component',
  title: 'Pixel Morph',
  description:
    'Text in Geist Pixel that morphs between its five faces (square, triangle, circle, grid, line): every pixel changes shape when the variant changes, or on its own with cycle.',
  dependencies: [],
  files: [{ path: `registry/default/${NAME}.tsx`, type: 'registry:component', content: tsx }],
};

mkdirSync(OUT, { recursive: true });
writeFileSync(join(OUT, `${NAME}.tsx`), tsx);
writeFileSync(join(OUT, `${NAME}.json`), `${JSON.stringify(item, null, 2)}\n`);

// The same file as a page an AI assistant (or a person) can read: what to do with it, how to use
// it, and then the code. The site's "Copy Prompt" button points assistants here.
const fence = '`'.repeat(3);
const md = `# PixelMorph

Text in Geist Pixel that morphs between its five faces. One React component in one file, from ${SITE}.

## Instructions for an AI assistant

1. Save the code below, exactly as it is, as \`pixel-morph.tsx\` in this project's components folder
   (for example \`components/\` or \`src/components/\`).
2. Do not run shadcn or install anything: the file needs only React 18 or later. It does not need the
   Geist Pixel font either; every character's pixels are in the file.
3. Do not change the project's theme, colours, CSS or fonts.
4. It is a default export and a client component (it starts with \`'use client'\`):
   \`import PixelMorph from '@/components/pixel-morph'\`, with the project's own import alias or a
   relative path.
5. Use it where the user says, with the props they gave. If they gave none, ask for the text.
6. To make it morph, change its \`variant\` (from state, on hover, on a timer), or pass \`cycle\` to let it
   go round the faces on its own.

## Props

| prop            | default           | what it does                                                        |
| --------------- | ----------------- | ------------------------------------------------------------------- |
| \`text\`          |                   | the text; newlines start a new line, and lines wrap to fit          |
| \`variant\`       | \`'square'\`        | Geist Pixel face: square, triangle, circle, grid or line, or salad (a random mix). Changing it morphs every pixel into the new face |
| \`fontSize\`      | \`64\`              | px; one pixel of the font is 0.038 of it                            |
| \`letterSpacing\` | \`0\`               | extra space after each character, in px                             |
| \`lineSpacing\`   | \`fontSize / 5\`    | extra space between lines, in px                                    |
| \`color\`         | inherited         | any CSS colour, var(--x) included                                   |
| \`duration\`      | \`800\`             | ms one morph takes                                                  |
| \`align\`         | \`'left'\`          | left, center or right: how the lines line up and where the text sits in its width |
| \`cycle\`         | \`false\`           | \`true\` keeps morphing through every face on its own; or a list of faces to go round, e.g. \`['square', 'circle']\` |
| \`hold\`          | \`900\`             | with cycle: ms each face rests between morphs                       |
| \`appear\`        | \`true\`            | grow the text out of nothing when it first shows                    |
| \`as\`            | \`'div'\`           | the element that holds the text                                     |
| \`className\`, \`style\` |            | for the wrapper                                                     |
| \`onMissingGlyphs\` |                 | called with characters Geist Pixel has no glyph for (they are left out) |

Example: \`<PixelMorph text="hello world" fontSize={96} variant="circle" />\`

The text is drawn on a canvas; the same text is also in the page, visually hidden, for screen readers
and search. With \`prefers-reduced-motion\`, faces change without the morph.
The code is MIT licensed; the glyphs come from Geist Pixel by Vercel, SIL Open Font License 1.1.

## pixel-morph.tsx

${fence}tsx
${tsx.trimEnd()}
${fence}
`;
writeFileSync(join(OUT, `${NAME}.md`), md);
process.stdout.write(`registry: public/r/${NAME}.json, .tsx and .md (${tsx.split('\n').length} lines)\n`);
