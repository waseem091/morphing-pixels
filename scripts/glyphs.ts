// Reads every character's pixels out of Geist Pixel and writes them to
// src/morph/glyph-data.ts, so the page never has to rasterise the font.
//
// All five Geist Pixel faces put their pixels on the same 38-unit lattice and
// share one bitmap per character; they only draw each pixel differently. Grid
// is the easiest to read: every pixel is its own 30-unit square, 4 units into
// its cell, so each contour's corner gives the cell directly.
//
//   npm run glyphs
import { writeFileSync } from 'node:fs';
import * as fontkit from 'fontkit';
import { ALPHABET, ROW_BIAS, X_BIAS } from '../src/morph/encoding.ts';

const SRC = 'public/fonts/GeistPixel-Grid.woff2';
const OUT = 'src/morph/glyph-data.ts';
const STEP = 38;
const INSET = 4;

const font = fontkit.openSync(SRC);
if (font.unitsPerEm !== 1000) throw new Error(`expected 1000 units per em, got ${font.unitsPerEm}`);

function char(n: number): string {
  if (!Number.isInteger(n) || n < 0 || n >= ALPHABET.length) throw new Error(`cannot encode ${n}`);
  return ALPHABET[n];
}

const glyphs: Record<number, string> = {};
let pixels = 0;

for (const cp of [...font.characterSet].sort((a, b) => a - b)) {
  const glyph = font.glyphForCodePoint(cp);
  if (!glyph || glyph.id === 0) continue;

  // One contour per pixel; composites (accents, the dot on i) are already
  // flattened into their parts by fontkit.
  const cells = new Set<string>();
  let xs: number[] = [];
  let ys: number[] = [];
  const close = () => {
    if (!xs.length) return;
    // Accents sit half a cell over on a few letters (Å, ů, ș…), so x is kept in
    // half cells. A handful of accents are 1 unit off the lattice vertically,
    // which rounding puts back.
    const halfX = Math.round(((Math.min(...xs) - INSET) / STEP) * 2);
    const bottom = Math.round((Math.min(...ys) - INSET) / STEP);
    // Rows count down from the baseline: the row just above it is -1.
    cells.add(`${-(bottom + 1)},${halfX}`);
    xs = [];
    ys = [];
  };
  for (const { command, args } of glyph.path.commands) {
    if (command === 'moveTo') close();
    if (command === 'closePath') {
      close();
      continue;
    }
    for (let i = 0; i < args.length; i += 2) {
      xs.push(args[i]);
      ys.push(args[i + 1]);
    }
  }
  close();

  // Row by row, left to right, as runs of whole pixels: [row, x, length].
  const sorted = [...cells].map((c) => c.split(',').map(Number)).sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  let data = char(Math.round(glyph.advanceWidth / STEP));
  for (let i = 0; i < sorted.length; ) {
    const [row, x] = sorted[i];
    let n = 1;
    while (i + n < sorted.length && sorted[i + n][0] === row && sorted[i + n][1] === x + 2 * n) n++;
    data += char(row + ROW_BIAS) + char(x + X_BIAS) + char(n);
    i += n;
  }
  glyphs[cp] = data;
  pixels += sorted.length;
}

const body = Object.entries(glyphs)
  .map(([cp, data]) => `  ${cp}: '${data}',`)
  .join('\n');

writeFileSync(
  OUT,
  `// Generated by \`npm run glyphs\` (scripts/glyphs.ts) from ${SRC}. Do not edit.
// Code point -> advance, then [row, half-cell x, length] runs; see encoding.ts.
export const GLYPHS: Record<number, string> = {
${body}
};
`,
);

console.log(`${Object.keys(glyphs).length} characters, ${pixels} pixels -> ${OUT}`);
